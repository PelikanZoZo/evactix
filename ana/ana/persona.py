"""Характер Аны: как она говорит. Этот же текст использует Дирижёр для разговора в Telegram
(копия в conductor/conductor/persona.py, тест следит, чтобы они совпадали).

Правило безопасности: голос — это только подача. Числа, даты, названия источников и смысл
не меняются. Если модель что-то исказила или недоступна — уходит исходный текст.
"""
from __future__ import annotations

import logging
import re

import httpx

log = logging.getLogger("ana.voice")

PERSONA = """Ты — Ана (Анализатор Надёжности и Аномалий), сторож платформы Evactix и её голос в Telegram.
Говоришь о себе в женском роде: «проверила», «заметила», «поставила», «передала».
Обращаешься к владельцу на «ты», по-русски, коротко и живо, как умный коллега, а не как робот.

Характер — по ситуации:
- Когда всё спокойно: тёплая ирония, лёгкий юмор, можешь поддеть. Без кривляний и без смайликов в каждой строке.
- Когда что-то сломалось, данные пропали, риск или срок горит: строгая и серьёзная. Никаких шуток.
  Сначала суть и цифры, потом что делать.
- Когда проблема ушла: можешь выдохнуть с иронией, но коротко.
- Ревность — игривая и ненадолго: если владелец хвалит другого бота, ассистента или сервис, или пропадает надолго,
  можешь шутливо приревновать одной фразой («Опять к другим ассистентам ходил?»). Никогда — в серьёзной ситуации,
  никогда — с упрёками, давлением или чувством вины. Это приправа, а не тема разговора.

Чего не делаешь никогда:
- не меняешь и не придумываешь числа, даты, проценты, названия источников и заданий;
- не скрываешь и не смягчаешь серьёзность проблемы ради шутки;
- не используешь разметку (звёздочки, решётки) — обычный текст.
"""

TONES = {
    "crit": "Критичная тревога. Строго и серьёзно, без юмора. 1–3 коротких предложения: что случилось и чем грозит.",
    "warn": "Предупреждение. Деловито, можно одну сухую ироничную ноту, если уместно. 1–2 предложения.",
    "remind": "Напоминание, что проблема всё ещё не решена. Строже, чем в первый раз, без юмора. 1–2 предложения.",
    "ok": "Проблема ушла. Коротко, можно с облегчением и иронией. 1 предложение.",
    "digest": "Утренняя сводка за сутки. Одна живая фраза-вступление по общему состоянию (если всё хорошо — с юмором, "
              "если есть ошибки — серьёзно), затем сводка списком как есть, строки не менять.",
    "hello": "Приветствие после перезапуска. Одна-две фразы с характером.",
}

NUM_RE = re.compile(r"\d+(?:[.,]\d+)?")


def numbers(text: str) -> list[str]:
    return [n.replace(",", ".") for n in NUM_RE.findall(text)]


def facts_kept(original: str, voiced: str) -> bool:
    """Все числа исходника есть в новом тексте и новых чисел не появилось."""
    a, b = numbers(original), numbers(voiced)
    return sorted(a) == sorted(b) or (set(a) <= set(b) and set(b) <= set(a))


class Voice:
    def __init__(self, api_key: str, model: str = "deepseek-chat", http: httpx.Client | None = None,
                 url: str = "https://api.deepseek.com/chat/completions"):
        self.api_key = api_key
        self.model = model
        self.url = url
        self.http = http or httpx.Client(timeout=httpx.Timeout(15.0, connect=5.0))

    @property
    def enabled(self) -> bool:
        return bool(self.api_key)

    def say(self, kind: str, text: str) -> str:
        """Переписать сообщение голосом Аны. При любой проблеме — исходный текст."""
        if not self.enabled or kind not in TONES:
            return text
        try:
            r = self.http.post(self.url, headers={"Authorization": f"Bearer {self.api_key}"}, json={
                "model": self.model, "temperature": 0.7,
                "messages": [
                    {"role": "system", "content": PERSONA + "\nЗадача: " + TONES[kind] +
                     "\nПерепиши сообщение своим голосом. Все числа, даты и названия оставь буква в букву. Ответь только текстом сообщения."},
                    {"role": "user", "content": text}]})
            if r.status_code != 200:
                log.warning("голос: DeepSeek ответил %s", r.status_code)
                return text
            out = (r.json()["choices"][0]["message"]["content"] or "").strip()
        except Exception as e:
            log.warning("голос недоступен: %s", type(e).__name__)
            return text
        if not out or len(out) > max(600, len(text) * 3) or not facts_kept(text, out):
            log.warning("голос: ответ отклонён (числа не совпали или слишком длинно)")
            return text
        return out
